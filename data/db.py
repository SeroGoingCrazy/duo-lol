"""Storage: a SQLite file, or Postgres (Neon) when the target is a postgres:// URL. One row per match
and per participant; pairs (同队任意两人, ADR-0002) and champion proficiency (本赛季单双排用某英雄的局数和胜率)
are derived from participants.

SQL is written once, with ? placeholders and syntax both databases accept; is_postgres() marks the
few queries that differ. The target comes from --db, else DUO_DB, else DATABASE_URL (default_target).
"""
import os
import re
import sqlite3
import threading
from pathlib import Path

from dotenv import load_dotenv

SCHEMA = """
CREATE TABLE IF NOT EXISTS players (
    puuid TEXT PRIMARY KEY,
    riot_id TEXT,              -- gameName#tagLine, filled from match data
    tier TEXT, division TEXT, league_points INTEGER,
    wins INTEGER, losses INTEGER,
    sampled_at INTEGER,
    recommend_opt_in INTEGER NOT NULL DEFAULT 0  -- PRD §7: only opted-in players join the pool at launch
);
CREATE TABLE IF NOT EXISTS matches (
    match_id TEXT PRIMARY KEY,
    seed_tier TEXT,            -- stratum the match was sampled from
    game_version TEXT,
    game_creation INTEGER, game_duration INTEGER
);
CREATE TABLE IF NOT EXISTS participants (
    match_id TEXT, puuid TEXT, team_id INTEGER, win INTEGER,
    position TEXT, champion_id INTEGER, champion_name TEXT,
    kills INTEGER, deaths INTEGER, assists INTEGER,
    gold INTEGER, damage INTEGER, cs INTEGER, vision INTEGER,
    PRIMARY KEY (match_id, puuid)
);
CREATE INDEX IF NOT EXISTS idx_part_puuid ON participants(puuid);
CREATE INDEX IF NOT EXISTS idx_part_champ ON participants(champion_name, position);
CREATE TABLE IF NOT EXISTS player_cache (   -- 查过的玩家 (PRD §4 缓存)
    puuid TEXT PRIMARY KEY,
    riot_id TEXT NOT NULL,       -- gameName#tagLine as Riot returns it
    riot_id_key TEXT NOT NULL,   -- lower-cased, for lookups
    tier TEXT, division TEXT, league_points INTEGER,
    match_ids TEXT NOT NULL,     -- JSON list: this season's Solo/Duo games used for the profile
    fetched_at INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_cache_riot_id ON player_cache(riot_id_key);
CREATE TABLE IF NOT EXISTS ladder (         -- 天梯快照: every NA Solo/Duo entry, so teammates have a tier (段位差)
    puuid TEXT PRIMARY KEY,
    tier TEXT, division TEXT, league_points INTEGER,
    wins INTEGER, losses INTEGER,
    fetched_at INTEGER
);
CREATE INDEX IF NOT EXISTS idx_ladder_tier ON ladder(tier);
CREATE TABLE IF NOT EXISTS ladder_progress (  -- resume point of the ladder crawl
    tier TEXT, division TEXT, last_page INTEGER NOT NULL DEFAULT 0, done INTEGER NOT NULL DEFAULT 0,
    PRIMARY KEY (tier, division)
);
CREATE TABLE IF NOT EXISTS key_epoch (        -- PUUIDs are encrypted per API key; a key that sees new ones starts an epoch
    id INTEGER PRIMARY KEY,
    probes TEXT NOT NULL,                     -- JSON [[riot_id, puuid], ...] as this key sees them
    matches_before INTEGER NOT NULL,          -- matches with rowid <= this still carry the previous key's PUUIDs
    started_at INTEGER NOT NULL,
    done INTEGER NOT NULL DEFAULT 0           -- 1 once those matches are re-keyed
);
CREATE TABLE IF NOT EXISTS rekeyed (          -- matches whose participants were moved to the epoch's PUUIDs
    match_id TEXT PRIMARY KEY, epoch INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS seed_progress (    -- seed players whose recent games are already stored
    puuid TEXT PRIMARY KEY,
    matches_per_player INTEGER NOT NULL       -- how many recent games were requested
);
CREATE TABLE IF NOT EXISTS champion_stats (   -- 全服统计 summed by sync_site.py, for a site database without raw matches
    champion_name TEXT, position TEXT, tier TEXT,  -- tier = the match's seed tier, like OwnDataSource
    wins INTEGER NOT NULL, games INTEGER NOT NULL,
    PRIMARY KEY (champion_name, position, tier)
);
CREATE TABLE IF NOT EXISTS pair_stats (       -- 英雄组合 on one team, all tiers; (champ_a, pos_a) sorts before (champ_b, pos_b)
    champ_a TEXT, pos_a TEXT, champ_b TEXT, pos_b TEXT,
    wins INTEGER NOT NULL, games INTEGER NOT NULL,
    PRIMARY KEY (champ_a, pos_a, champ_b, pos_b)
);
CREATE TABLE IF NOT EXISTS score_scale (      -- 搭配评分 scale (score_scale.py); one row, shared by every API machine
    id INTEGER PRIMARY KEY CHECK (id = 1),
    scale TEXT NOT NULL,                      -- JSON written by score_scale.fit
    fitted_at INTEGER NOT NULL
);
"""


# Postgres differences: game_creation is in milliseconds (past 32-bit INTEGER), key_epoch ids need an
# identity column, and seq numbers matches in insertion order, which SQLite's rowid gives key_epoch.
PG_SCHEMA = (
    SCHEMA.replace("game_creation INTEGER", "game_creation BIGINT")
    .replace("id INTEGER PRIMARY KEY,", "id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,")
    .replace("game_duration INTEGER\n", "game_duration INTEGER,\n    seq BIGSERIAL\n")
    + "CREATE INDEX IF NOT EXISTS idx_matches_seq ON matches(seq);\n"
)
TABLES = re.findall(r"CREATE TABLE IF NOT EXISTS (\w+)", SCHEMA)
_pg_ready = set()
_pg_lock = threading.Lock()


def default_target():
    """DUO_DB (a SQLite path or a Postgres URL), else DATABASE_URL, else lol_duo.sqlite.
    Reads the repo-root .env (or the file DUO_ENV names) like riot.py."""
    load_dotenv(os.environ.get("DUO_ENV") or Path(__file__).resolve().parent.parent / ".env")
    return os.environ.get("DUO_DB") or os.environ.get("DATABASE_URL") or "lol_duo.sqlite"


def is_url(target):
    return str(target).startswith(("postgres://", "postgresql://"))


def connect(target):
    if is_url(target):
        return PgConnection(target)
    # Lookup threads write while the site reads; WAL + a busy timeout keeps them from failing.
    conn = sqlite3.connect(target, timeout=30)
    conn.execute("PRAGMA journal_mode=WAL")
    conn.executescript(SCHEMA)
    return conn


def is_postgres(conn):
    return isinstance(conn, PgConnection)


def match_order(conn):
    """Column that numbers matches in the order they were stored."""
    return "seq" if is_postgres(conn) else "rowid"


class PgConnection:
    """A psycopg connection used like sqlite3's: conn.execute / executemany with ? placeholders,
    commit, and `with conn:` committing on success.

    The tables live in the `data` schema; the site's are in `app` (ADR-0004). A URL that sets its own
    search_path (the tests do) keeps it."""

    def __init__(self, url):
        import psycopg
        from psycopg.conninfo import conninfo_to_dict
        # Neon's pooled endpoint (-pooler) is PgBouncer in transaction mode, which drops the search_path;
        # one connection per run or request is few enough for the direct endpoint.
        params = conninfo_to_dict(url)
        if "host" in params:
            params["host"] = params["host"].replace("-pooler.", ".", 1)
        options = params.get("options", "")
        own_path = "search_path" in options
        if not own_path:
            params["options"] = f"{options} -c search_path=data".strip()
        self.raw = psycopg.connect(**params)
        with _pg_lock:
            if url not in _pg_ready:
                self._create_tables(own_path)
                _pg_ready.add(url)

    def _create_tables(self, own_path):
        # Only when a table is missing: even IF NOT EXISTS DDL waits for the collector's open transaction.
        have = self.raw.execute("SELECT count(*) FROM pg_tables WHERE schemaname = current_schema()"
                                " AND tablename = ANY(%s)", (TABLES,)).fetchone()[0]
        if have < len(TABLES):
            self.raw.execute("SELECT pg_advisory_xact_lock(4242)")   # one process creates the tables
            if not own_path:
                self.raw.execute("CREATE SCHEMA IF NOT EXISTS data")
            self.raw.execute(PG_SCHEMA)
        self.raw.commit()

    @staticmethod
    def _sql(sql, params):
        return sql.replace("%", "%%").replace("?", "%s") if params else sql

    def execute(self, sql, params=()):
        return self.raw.execute(self._sql(sql, params), params or None)

    def executemany(self, sql, rows):
        rows = list(rows)
        cur = self.raw.cursor()
        if rows:
            cur.executemany(self._sql(sql, rows[0]), rows)   # pipelined: one round trip to Neon
        return cur

    def commit(self):
        self.raw.commit()

    def rollback(self):
        self.raw.rollback()

    def close(self):
        self.raw.close()

    def __enter__(self):
        return self

    def __exit__(self, exc_type, *_):
        if exc_type:
            self.raw.rollback()
        else:
            self.raw.commit()


def has_match(conn, match_id):
    return conn.execute("SELECT 1 FROM matches WHERE match_id=?", (match_id,)).fetchone() is not None


def save_player(conn, entry, now):
    conn.execute(
        """INSERT INTO players (puuid, tier, division, league_points, wins, losses, sampled_at)
           VALUES (?,?,?,?,?,?,?)
           ON CONFLICT(puuid) DO UPDATE SET tier=excluded.tier, division=excluded.division,
             league_points=excluded.league_points, wins=excluded.wins, losses=excluded.losses,
             sampled_at=excluded.sampled_at""",
        (entry["puuid"], entry["tier"], entry["rank"], entry["leaguePoints"],
         entry["wins"], entry["losses"], now),
    )


def save_ladder(conn, entries, now):
    conn.executemany(
        """INSERT INTO ladder VALUES (?,?,?,?,?,?,?)
           ON CONFLICT(puuid) DO UPDATE SET tier=excluded.tier, division=excluded.division,
             league_points=excluded.league_points, wins=excluded.wins, losses=excluded.losses,
             fetched_at=excluded.fetched_at""",
        [(e["puuid"], e["tier"], e["rank"], e["leaguePoints"], e["wins"], e["losses"], now)
         for e in entries if e.get("puuid")],
    )


def has_participant(conn, match_id, puuid):
    return conn.execute("SELECT 1 FROM participants WHERE match_id=? AND puuid=?",
                        (match_id, puuid)).fetchone() is not None


def rekey_participants(conn, match):
    """Replace a cached match's PUUIDs with the ones this API key sees. A champion appears once
    per game, so (match_id, champion_name) finds the same participant under either key."""
    mid = match["metadata"]["matchId"]
    parts = match["info"]["participants"]
    conn.executemany("UPDATE participants SET puuid=? WHERE match_id=? AND champion_name=?",
                     [(p["puuid"], mid, p["championName"]) for p in parts])
    save_riot_ids(conn, parts)


def save_riot_ids(conn, participants):
    conn.executemany(
        "INSERT INTO players (puuid, riot_id) VALUES (?, ?) ON CONFLICT(puuid) DO UPDATE SET riot_id=excluded.riot_id",
        [(p["puuid"], f'{p["riotIdGameName"]}#{p.get("riotIdTagline", "")}')
         for p in participants if p.get("riotIdGameName")],
    )


def save_match(conn, match, seed_tier):
    info = match["info"]
    if info.get("queueId") != 420:
        return False
    conn.execute(
        """INSERT INTO matches (match_id, seed_tier, game_version, game_creation, game_duration)
           VALUES (?,?,?,?,?) ON CONFLICT DO NOTHING""",
        (match["metadata"]["matchId"], seed_tier, info.get("gameVersion"),
         info.get("gameCreation"), info.get("gameDuration")),
    )
    conn.executemany(
        "INSERT INTO participants VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?) ON CONFLICT DO NOTHING",
        [(match["metadata"]["matchId"], p["puuid"], p["teamId"], int(p["win"]),
          p.get("teamPosition") or p.get("individualPosition"), p["championId"], p["championName"],
          p["kills"], p["deaths"], p["assists"], p["goldEarned"],
          p["totalDamageDealtToChampions"],
          p["totalMinionsKilled"] + p.get("neutralMinionsKilled", 0), p["visionScore"])
         for p in info["participants"]],
    )
    save_riot_ids(conn, info["participants"])
    return True


PARTY_HINTS = ("party", "premade", "group", "duo")


def party_fields(match):
    """Participant keys that might expose premade info (ADR-0002 assumes none exist)."""
    keys = set()
    for p in match["info"]["participants"]:
        keys |= {k for k in p if any(h in k.lower() for h in PARTY_HINTS)}
    return sorted(keys)
